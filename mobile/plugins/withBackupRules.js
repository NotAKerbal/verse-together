// Android backup rules: everything Android's Auto Backup includes by default (the study in SQLite under files/,
// reader settings), except expo-secure-store's preferences file, which holds the sign-in session encrypted with an
// Android Keystore key that is never backed up, so a restored copy could not be decrypted (the restored app is
// signed out instead). expo-secure-store's own rules (its `configureAndroidBackup`, switched off in app.json)
// `<include>` only shared preferences, which would silently drop the study database from backups.

const fs = require("fs");
const path = require("path");
const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins");

const BACKUP_RULES = "verse_backup_rules";
const EXTRACTION_RULES = "verse_data_extraction_rules";
// expo-secure-store's SharedPreferences name ("SecureStore"), as the file Android backs up.
const SECURE_STORE_FILE = "SecureStore.xml";

const exclude = `<exclude domain="sharedpref" path="${SECURE_STORE_FILE}"/>`;

/** Android 11 and lower. No <include>: everything else stays in the default backup. */
const backupRulesXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withBackupRules.js. -->
<full-backup-content>
  ${exclude}
</full-backup-content>
`;

/** Android 12 and higher: cloud backup and device-to-device transfer. */
const extractionRulesXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withBackupRules.js. -->
<data-extraction-rules>
  <cloud-backup>
    ${exclude}
  </cloud-backup>
  <device-transfer>
    ${exclude}
  </device-transfer>
</data-extraction-rules>
`;

function applyBackupRules(manifest) {
  const application = manifest.manifest.application?.[0];
  if (!application) throw new Error("withBackupRules: AndroidManifest.xml has no <application>.");
  application.$["android:fullBackupContent"] = `@xml/${BACKUP_RULES}`;
  application.$["android:dataExtractionRules"] = `@xml/${EXTRACTION_RULES}`;
  return manifest;
}

const withBackupRules = (config) => {
  config = withAndroidManifest(config, (mod) => {
    mod.modResults = applyBackupRules(mod.modResults);
    return mod;
  });
  return withDangerousMod(config, [
    "android",
    async (mod) => {
      const dir = path.join(mod.modRequest.platformProjectRoot, "app/src/main/res/xml");
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, `${BACKUP_RULES}.xml`), backupRulesXml);
      await fs.promises.writeFile(path.join(dir, `${EXTRACTION_RULES}.xml`), extractionRulesXml);
      return mod;
    },
  ]);
};

module.exports = withBackupRules;
module.exports.applyBackupRules = applyBackupRules;
module.exports.backupRulesXml = backupRulesXml;
module.exports.extractionRulesXml = extractionRulesXml;
